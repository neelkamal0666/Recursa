"""The storage interface every backend implements.

Two protocols, because the two sides hold different secrets and get different
credentials in Recursa Server (see the design doc, *Deployment modes*):

- ``RecordStore``: runs, scores, eval cache, feedback, versions and deployments,
  candidates, insights, approvals, the audit log and cycle checkpoints.
- ``SealedStore``: the gate side: runs and scores of evaluations on the sealed gate
  and confirmation sets (their inputs are sealed examples), the gate-budget ledger,
  gate checkpoints and review packets. The optimizer never gets one.

Both include ``EvalRunStore``, the part the eval runner needs.

Semantics every backend must honour (checked by ``tests/test_store_contract.py``):

- **Append-only records.** Nothing here updates or deletes a run, score, feedback
  item, version, deployment, approval, insight, audit entry, ledger entry or packet.
  The only mutable state is a candidate's status and cycle checkpoints.
- **Idempotent writes.** Writing a record whose id already exists is a no-op (the
  first write wins), so a client can retry after a timeout without duplicates.
  Feedback is idempotent by ``idempotency_key``; ``ledger_add`` reports whether it
  charged the budget.
- **Redaction before storage.** Run payloads and feedback corrections pass through
  the store's redactor; if redaction fails, the payload is dropped and only metrics
  are kept (``redaction == "unredacted_dropped"``).
- **Pagination.** List methods take ``limit`` and a cursor taken from the last item
  of the previous page (a run id, an audit ``seq``, a candidate id), so a remote
  backend never has to return an unbounded list.
- **Transfer format.** ``export_records``/``import_records`` exchange rows in the
  SQLite column layout (JSON columns as text, e.g. ``input_json``), whatever the
  backend, so a local scratch store can be imported into any other. Importing
  re-applies the importing store's redaction.
- **Missing records** return ``None`` (or an empty list), never raise, except
  ``put_feedback`` on an unknown run, which raises ``KeyError``.
"""
from __future__ import annotations

from typing import Any, Protocol, runtime_checkable

from ..types import Candidate, Run, Score


@runtime_checkable
class EvalRunStore(Protocol):
    """What ``recursa.evals.run_eval`` needs: runs, their scores and the eval cache."""

    def close(self) -> None: ...
    def put_run(self, run: Run) -> None: ...
    def get_run(self, run_id: str) -> dict[str, Any] | None: ...
    def put_scores(self, scores: list[Score]) -> None: ...
    def scores_for(self, run_id: str) -> list[Score]: ...
    def cache_get(self, key: str) -> str | None: ...
    def cache_put(self, key: str, run_id: str) -> None: ...


@runtime_checkable
class RecordStore(EvalRunStore, Protocol):
    # -- runs, scores, eval cache ------------------------------------------------------------
    def put_run(self, run: Run) -> None: ...
    def put_runs(self, runs: list[Run]) -> int:
        """Batch put (e.g. shipping the write-ahead log); returns how many were new."""
        ...
    def get_run(self, run_id: str) -> dict[str, Any] | None: ...
    def list_runs(self, mode: str | None = None, limit: int = 100,
                  before: str | None = None) -> list[dict[str, Any]]:
        """Newest first. ``before`` is the id of the last run on the previous page."""
        ...
    def put_scores(self, scores: list[Score]) -> None: ...
    def scores_for(self, run_id: str) -> list[Score]: ...
    def cache_get(self, key: str) -> str | None: ...
    def cache_put(self, key: str, run_id: str) -> None: ...

    # -- bulk transfer (optimizer worker -> main store) ------------------------------------
    def export_records(self) -> dict[str, list[dict[str, Any]]]: ...
    def import_records(self, records: dict[str, list[dict[str, Any]]]) -> float:
        """Append rows exported by another store; returns the cost of runs that were new."""
        ...

    # -- feedback ----------------------------------------------------------------------------
    def put_feedback(self, run_id: str, kind: str, value: float | None, correction: Any, author: str,
                     idempotency_key: str | None) -> str: ...
    def feedback_for(self, run_id: str) -> list[dict[str, Any]]: ...

    # -- versions and deployments ------------------------------------------------------------
    def put_version(self, parent: str | None, config: dict[str, Any], candidate_id: str | None,
                    approvers: list[str]) -> str:
        """Allocates the next id (``v1``, ``v2``, ...) atomically."""
        ...
    def get_version(self, vid: str) -> dict[str, Any] | None: ...
    def list_versions(self) -> list[dict[str, Any]]: ...
    def deploy(self, version_id: str, action: str, actor: str, reason: str = "") -> None: ...
    def current_version(self) -> str | None: ...
    def deployments(self) -> list[dict[str, Any]]: ...

    # -- candidates and insights -------------------------------------------------------------
    def put_candidate(self, c: Candidate) -> None: ...
    def set_candidate_status(self, cid: str, status: str) -> None: ...
    def get_candidate(self, cid: str) -> Candidate | None: ...
    def list_candidates(self, status: str | None = None, limit: int | None = None,
                        after: str | None = None) -> list[Candidate]:
        """Oldest first. ``after`` is the id of the last candidate on the previous page."""
        ...
    def put_insight(self, cycle_id: str, insight: dict[str, Any]) -> None: ...
    def get_insights(self, ids: list[str]) -> list[dict[str, Any]]: ...

    # -- approvals and audit -----------------------------------------------------------------
    def put_approval(self, candidate_id: str, reviewer: str, decision: str, reason: str, channel: str,
                     packet_hash: str) -> str: ...
    def approvals_for(self, candidate_id: str) -> list[dict[str, Any]]: ...
    def audit(self, actor: str, action: str, subject: str, details: dict[str, Any] | None = None) -> None: ...
    def audit_log(self, after: int = 0, limit: int | None = None) -> list[dict[str, Any]]:
        """Oldest first. ``after`` is the ``seq`` of the last entry on the previous page."""
        ...
    def verify_audit_chain(self) -> bool: ...

    # -- cycle checkpoints -------------------------------------------------------------------
    def save_cycle(self, cycle_id: str, state: dict[str, Any]) -> None: ...
    def load_cycle(self, cycle_id: str) -> dict[str, Any] | None: ...


@runtime_checkable
class SealedStore(EvalRunStore, Protocol):

    # -- gate budget ledger ------------------------------------------------------------------
    def ledger_add(self, gate_version: str, candidate_id: str, kind: str) -> bool:
        """Charge one evaluation to ``gate_version``. False if this candidate was already charged."""
        ...
    def ledger_count(self, gate_version: str, kind: str) -> int: ...
    def ledger_has(self, gate_version: str, candidate_id: str, kind: str) -> bool: ...

    # -- gate checkpoints --------------------------------------------------------------------
    def save_cycle(self, cycle_id: str, state: dict[str, Any]) -> None: ...
    def load_cycle(self, cycle_id: str) -> dict[str, Any] | None: ...

    # -- review packets ----------------------------------------------------------------------
    def put_packet(self, candidate_id: str, packet: dict[str, Any]) -> str: ...
    def latest_packet(self, candidate_id: str) -> tuple[str, dict[str, Any]] | None: ...
